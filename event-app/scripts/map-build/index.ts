#!/usr/bin/env -S node --import tsx
/**
 * Builds the venue map bundle from the floor-plan SVGs.
 *
 *   pnpm map:build            write plan.generated.json, rooms.generated.json, icons.generated.ts
 *   pnpm map:check            exit 1 when the committed outputs are stale (CI)
 *   pnpm map:build --verbose  also print the INFO lines (per-floor counts, scale)
 *
 * Inputs: the SVGs listed in src/app/(page-layout)/map/venue-map/data/levels.ts
 * and the area catalogue beside it. Any ERROR exits 1 and writes nothing.
 */
import fs from "node:fs";
import { buildBundle, buildRooms, iconNames } from "./build";
import { BUNDLE_PATH, ICON_NAMES_PATH, ROOMS_PATH } from "./config";
import { Report } from "./report";
import type { MapBundle } from "../../src/app/(page-layout)/map/venue-map/data/planSchema";

/** Compact JSON with one shape per line: diffs show which footprint moved, and the file stays small. */
function serializeBundle(bundle: MapBundle): string {
  const levels = bundle.levels.map((l) => {
    const head = JSON.stringify({ id: l.id, label: l.label, name: l.name, bounds: l.bounds }).slice(1, -1);
    return `  {${head},"shapes":[\n${l.shapes.map((s) => `   ${JSON.stringify(s)}`).join(",\n")}\n  ]}`;
  });
  return `{"version":2,"units":${JSON.stringify(bundle.units)},"bounds":${JSON.stringify(bundle.bounds)},"levels":[\n${levels.join(",\n")}\n]}\n`;
}

const args = process.argv.slice(2);
const check = args.includes("--check");
const verbose = args.includes("--verbose");

const report = new Report(verbose);
const icons = iconNames();
const iconsSource = `// Generated by scripts/map-build from public/maps/devcon-8/icons. Do not edit.\nexport const ICON_NAMES = ${JSON.stringify(icons)} as const;\nexport type IconName = (typeof ICON_NAMES)[number];\nexport const iconUrl = (name: IconName) => \`/maps/devcon-8/icons/\${name}.png\`;\n`;

const bundle = buildBundle(report);
const rooms = bundle ? buildRooms(bundle, report) : null;
report.print();
if (!bundle || !rooms || report.errors.length) {
  console.error(`\nmap-build: ${report.errors.length} error(s), nothing written`);
  process.exit(1);
}

const outputs: [string, string][] = [
  [BUNDLE_PATH, serializeBundle(bundle)],
  [ROOMS_PATH, JSON.stringify(rooms, null, 2) + "\n"],
  [ICON_NAMES_PATH, iconsSource],
];
if (check) {
  const stale = outputs.filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content);
  if (stale.length) {
    console.error(`\nmap-build --check: stale ${stale.map(([f]) => f).join(", ")} — run pnpm map:build and commit`);
    process.exit(1);
  }
  console.log("map-build --check: outputs are current");
} else {
  for (const [file, content] of outputs) fs.writeFileSync(file, content);
  console.log(`\nmap-build: wrote ${outputs.map(([f]) => f.replace(/^.*\/venue-map\//, "")).join(", ")}`);
  for (const level of bundle.levels) {
    const counts = level.shapes.reduce<Record<string, number>>((acc, s) => ({ ...acc, [s.kind]: (acc[s.kind] ?? 0) + 1 }), {});
    console.log(`  ${level.id}: ${Object.entries(counts).map(([k, n]) => `${n} ${k}`).join(", ")}`);
  }
}
